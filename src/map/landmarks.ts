import type { LngLat } from "@/lib/geo";

/**
 * Curated Berlin destinations used by the "Places" menu and to seed the search
 * palette so common queries resolve instantly without touching the network.
 *
 * Each entry carries its own camera framing: a wide park wants a high, gentle
 * angle while a single tower wants to be looked up at, so a one-size flyTo
 * makes half of these land badly.
 */

export type LandmarkCategory =
  | "icon"
  | "square"
  | "museum"
  | "park"
  | "water"
  | "transport"
  | "district"
  | "stadium";

export interface Landmark {
  id: string;
  name: string;
  /** Shown under the name - what you would tell a visitor. */
  hint: string;
  category: LandmarkCategory;
  center: LngLat;
  zoom: number;
  pitch: number;
  bearing: number;
  /** Extra search terms (English names, nicknames, common misspellings). */
  aliases?: string[];
}

